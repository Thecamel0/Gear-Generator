function fig1 = plot_planetary_assembly_3d(sun_mesh, planet_mesh, ring_mesh, carrier_mesh, calc)
%PLOT_PLANETARY_ASSEMBLY_3D Generates 3D CAD Assembly and Exploded View
%   for a complete Epicyclic (Planetary) Gear Train: Sun, K Planets, Ring Gear, and Carrier.
%
%   - Subplot 1: Full 3D CAD Assembly with All Components in True Meshing Engagement
%   - Subplot 2: Exploded View showing Axial Disassembly of Carrier, Ring, Planets, and Sun
%
%   Author: Ahmed Majdy Ahmed
%   Date:   2026-09-11

    if nargin < 5
        error('plot_planetary_assembly_3d requires sun_mesh, planet_mesh, ring_mesh, carrier_mesh, and calc');
    end

    K = calc.K;
    C = calc.center_dist;
    Ns = calc.Ns;
    Np = calc.Np;
    Nr = calc.Nr;
    m = calc.m;

    fig1 = figure('Name', 'Planetary Suite — 3D CAD Assembly & Exploded View', ...
        'NumberTitle', 'off', ...
        'Position', [40, 40, 1450, 850], ...
        'Color', [0.08 0.08 0.11]);

    planet_colors = [
        0.45 0.58 0.78;   % Steel Blue
        0.55 0.75 0.55;   % Sage Green
        0.72 0.48 0.65;   % Dusty Lavender
        0.78 0.68 0.45;   % Warm Ochre
        0.50 0.70 0.75;   % Cyan Teal
        0.70 0.55 0.55    % Terra Cotta
    ];

    %% ====================================================================
    %  SUBPLOT 1: Full 3D CAD Assembly
    %  ====================================================================
    ax1 = subplot(1, 2, 1, 'Parent', fig1);
    hold(ax1, 'on');

    % 1. Internal Ring Gear (Golden Bronze)
    patch(ax1, 'Vertices', ring_mesh.vertices, ...
        'Faces', ring_mesh.faces, ...
        'VertexNormals', ring_mesh.normals, ...
        'FaceColor', [0.78 0.52 0.28], ...
        'EdgeColor', 'none', ...
        'FaceAlpha', 0.95, ...
        'FaceLighting', 'gouraud', ...
        'AmbientStrength', 0.40, ...
        'DiffuseStrength', 0.65, ...
        'SpecularStrength', 0.35);

    % 2. Central Sun Gear (Polished Silver / Chrome)
    % Initial clocking so tooth space aligns at theta = 0
    th_sun_init = pi / Ns;
    c_s = cos(th_sun_init); s_s = sin(th_sun_init);
    Rz_sun = [c_s -s_s 0; s_s c_s 0; 0 0 1];
    sun_v = (Rz_sun * sun_mesh.vertices')';
    sun_n = (Rz_sun * sun_mesh.normals')';

    patch(ax1, 'Vertices', sun_v, ...
        'Faces', sun_mesh.faces, ...
        'VertexNormals', sun_n, ...
        'FaceColor', [0.88 0.88 0.92], ...
        'EdgeColor', 'none', ...
        'FaceAlpha', 1.0, ...
        'FaceLighting', 'gouraud', ...
        'AmbientStrength', 0.45, ...
        'DiffuseStrength', 0.60, ...
        'SpecularStrength', 0.50);

    % 3. K Planet Gears at Orbit Radius C
    for k = 1:K
        th_k = (k - 1) * 2 * pi / K;
        cx = C * cos(th_k);
        cy = C * sin(th_k);

        % Rotational clocking for planet mesh:
        % Tooth pitch at mesh point aligned with line of centers
        phi_rot = th_k + th_k * (Ns / Np);
        c_p = cos(phi_rot); s_p = sin(phi_rot);
        Rz_p = [c_p -s_p 0; s_p c_p 0; 0 0 1];

        p_v = (Rz_p * planet_mesh.vertices')';
        p_v(:, 1) = p_v(:, 1) + cx;
        p_v(:, 2) = p_v(:, 2) + cy;
        p_n = (Rz_p * planet_mesh.normals')';

        c_idx = mod(k - 1, size(planet_colors, 1)) + 1;
        patch(ax1, 'Vertices', p_v, ...
            'Faces', planet_mesh.faces, ...
            'VertexNormals', p_n, ...
            'FaceColor', planet_colors(c_idx, :), ...
            'EdgeColor', 'none', ...
            'FaceAlpha', 0.96, ...
            'FaceLighting', 'gouraud', ...
            'AmbientStrength', 0.40, ...
            'DiffuseStrength', 0.65, ...
            'SpecularStrength', 0.35);
    end

    % 4. Planet Carrier with Pins (Anthracite Grey with semi-transparent disc)
    patch(ax1, 'Vertices', carrier_mesh.vertices, ...
        'Faces', carrier_mesh.faces, ...
        'VertexNormals', carrier_mesh.normals, ...
        'FaceColor', [0.38 0.42 0.50], ...
        'EdgeColor', 'none', ...
        'FaceAlpha', 0.82, ...
        'FaceLighting', 'gouraud', ...
        'AmbientStrength', 0.40, ...
        'DiffuseStrength', 0.60, ...
        'SpecularStrength', 0.40);

    % Lighting & Scene Styling
    light(ax1, 'Position', [1 1 1.5], 'Style', 'infinite');
    light(ax1, 'Position', [-1 -1 1.0], 'Style', 'infinite');
    light(ax1, 'Position', [0 0 -1.5], 'Style', 'infinite');
    axis(ax1, 'equal'); grid(ax1, 'on');
    xlabel(ax1, 'X [mm]'); ylabel(ax1, 'Y [mm]'); zlabel(ax1, 'Z [mm]');
    title(ax1, sprintf('3D Planetary Assembly (m = %g mm, Ratio 1:%.1f, %d Planets)', ...
        m, calc.i_ratio, K), 'Color', 'w', 'FontSize', 12, 'FontWeight', 'bold');
    view(ax1, [-45 32]);
    set(ax1, 'Color', [0.12 0.12 0.16], ...
        'XColor', [0.7 0.7 0.7], 'YColor', [0.7 0.7 0.7], 'ZColor', [0.7 0.7 0.7], ...
        'GridColor', [0.25 0.25 0.30], 'GridAlpha', 0.5);

    %% ====================================================================
    %  SUBPLOT 2: Exploded Assembly View along Z
    %  ====================================================================
    ax2 = subplot(1, 2, 2, 'Parent', fig1);
    hold(ax2, 'on');

    z_sep = calc.F * 1.6;

    % 1. Carrier exploded downward (-Z)
    c_exp_v = carrier_mesh.vertices;
    c_exp_v(:, 3) = c_exp_v(:, 3) - z_sep * 1.5;
    patch(ax2, 'Vertices', c_exp_v, ...
        'Faces', carrier_mesh.faces, ...
        'VertexNormals', carrier_mesh.normals, ...
        'FaceColor', [0.38 0.42 0.50], ...
        'EdgeColor', 'none', ...
        'FaceAlpha', 0.88, ...
        'FaceLighting', 'gouraud');

    % 2. Ring Gear at Z = 0
    patch(ax2, 'Vertices', ring_mesh.vertices, ...
        'Faces', ring_mesh.faces, ...
        'VertexNormals', ring_mesh.normals, ...
        'FaceColor', [0.78 0.52 0.28], ...
        'EdgeColor', 'none', ...
        'FaceAlpha', 0.90, ...
        'FaceLighting', 'gouraud');

    % 3. Planets exploded slightly upward and outward
    for k = 1:K
        th_k = (k - 1) * 2 * pi / K;
        cx = (C + 6.0) * cos(th_k);
        cy = (C + 6.0) * sin(th_k);

        phi_rot = th_k + th_k * (Ns / Np);
        c_p = cos(phi_rot); s_p = sin(phi_rot);
        Rz_p = [c_p -s_p 0; s_p c_p 0; 0 0 1];

        p_v = (Rz_p * planet_mesh.vertices')';
        p_v(:, 1) = p_v(:, 1) + cx;
        p_v(:, 2) = p_v(:, 2) + cy;
        p_v(:, 3) = p_v(:, 3) + z_sep * 0.4;
        p_n = (Rz_p * planet_mesh.normals')';

        c_idx = mod(k - 1, size(planet_colors, 1)) + 1;
        patch(ax2, 'Vertices', p_v, ...
            'Faces', planet_mesh.faces, ...
            'VertexNormals', p_n, ...
            'FaceColor', planet_colors(c_idx, :), ...
            'EdgeColor', 'none', ...
            'FaceAlpha', 0.96, ...
            'FaceLighting', 'gouraud');

        % Centerline connecting carrier pin to exploded planet
        plot3(ax2, [cx, cx], [cy, cy], [-z_sep * 1.5, z_sep * 0.4], '-.', ...
            'Color', [0.6 0.6 0.7], 'LineWidth', 1.0);
    end

    % 4. Sun Gear exploded upward (+Z)
    sun_exp_v = sun_v;
    sun_exp_v(:, 3) = sun_exp_v(:, 3) + z_sep * 1.2;
    patch(ax2, 'Vertices', sun_exp_v, ...
        'Faces', sun_mesh.faces, ...
        'VertexNormals', sun_n, ...
        'FaceColor', [0.88 0.88 0.92], ...
        'EdgeColor', 'none', ...
        'FaceAlpha', 1.0, ...
        'FaceLighting', 'gouraud');

    % Centerline through axis of symmetry
    plot3(ax2, [0 0], [0 0], [-z_sep * 1.8, z_sep * 1.5], 'c-.', 'LineWidth', 1.2);

    % Subplot 2 Lighting & Scene Styling
    light(ax2, 'Position', [1 1 1.5], 'Style', 'infinite');
    light(ax2, 'Position', [-1 -1 1.0], 'Style', 'infinite');
    light(ax2, 'Position', [0 0 -1.5], 'Style', 'infinite');
    axis(ax2, 'equal'); grid(ax2, 'on');
    xlabel(ax2, 'X [mm]'); ylabel(ax2, 'Y [mm]'); zlabel(ax2, 'Z [mm]');
    title(ax2, 'Exploded Assembly View (Axial Decomposition)', ...
        'Color', 'w', 'FontSize', 12, 'FontWeight', 'bold');
    view(ax2, [-40 28]);
    set(ax2, 'Color', [0.12 0.12 0.16], ...
        'XColor', [0.7 0.7 0.7], 'YColor', [0.7 0.7 0.7], 'ZColor', [0.7 0.7 0.7], ...
        'GridColor', [0.25 0.25 0.30], 'GridAlpha', 0.5);

    % Annotation text block
    annotation(fig1, 'textbox', [0.38, 0.02, 0.24, 0.05], ...
        'String', sprintf('Sun: %dT | Planet: %dT (x%d) | Ring: %dT | Ratio: 1:%.1f', ...
            Ns, Np, K, Nr, calc.i_ratio), ...
        'EdgeColor', [0.3 0.3 0.4], 'BackgroundColor', [0.15 0.15 0.20], ...
        'Color', [0.9 0.9 0.9], 'FontWeight', 'bold', 'FontSize', 10, ...
        'HorizontalAlignment', 'center', 'VerticalAlignment', 'middle');
end
