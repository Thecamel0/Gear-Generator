%% ========================================================================
%  ZEROL BEVEL GEAR DESIGN V2 — Wind Turbine Pitch Control System
%  ========================================================================
%  Complete redesign using Gleason face-milling tooth geometry.
%
%  Key improvements over V1:
%    - TRUE Zerol bevel gear tooth curvature (circular-arc tooth traces)
%    - Lengthwise and profile crowning for reliable contact
%    - 3D print compensation (material-specific shrinkage & clearance)
%    - Tip relief to prevent interference
%    - Watertight mesh verification
%    - Cleaner code structure (modular functions)
%
%  Architecture:
%    Motor -> Worm Gearbox -> Central Ring Gear (48T, Driver)
%          -> 3 Zerol Pinions (16T, Driven) -> 3 Blade Pitch Shafts
%
%  Author:  Ahmed Majdy Ahmed
%  Date:    2026-08-24
% =========================================================================

clear; clc; close all;

%% --- Add paths ---
script_folder = fileparts(mfilename('fullpath'));
if ~isempty(script_folder)
    addpath(fullfile(script_folder, 'Core'));
    addpath(fullfile(script_folder, 'PrintComp'));
    addpath(fullfile(script_folder, 'Export'));
    addpath(fullfile(script_folder, 'Viz'));
end

%% ========================================================================
%  INPUT PARAMETERS
%  ========================================================================

% --- Gear Tooth Parameters ---
m       = 3.0;        % Module [mm] (gives 48 mm pinion PD & 144 mm gear PD)
Np      = 16;        % Pinion teeth (pitch diameter = 3.0 × 16 = 48 mm)
Ng      = 48;        % Ring gear teeth (pitch diameter = 3.0 × 48 = 144 mm)
phi_deg = 20;       % Pressure angle [deg] (standard Gleason value)
Sigma   = 90;       % Shaft angle [deg]

% --- Multi-Pinion Configuration ---
n_pinions = 3;      % 1 per blade (10 teeth per sector → perfect 120° symmetry)

% --- Gleason Cutter Parameters ---
% r_cutter controls the tooth curvature. Larger = gentler curve.
% Standard: r_cutter ≈ mean cone distance (Am).
% Set to Inf for straight bevel (no curvature).
r_cutter = [];      % [] = auto (use mean cone distance)

% --- Tooth Depth Factors ---
khw_factor = 2.00;  % Working depth = khw_factor * m  [Gleason standard: 2.00]
c_factor   = 0.188; % Clearance = c_factor * m        [Gleason standard: 0.188]

% --- Operating Conditions ---
T_in_ring   = 20;   % Input torque to ring gear [N·m] (5–20 range)
n_in_ring   = 100;  % Ring gear speed [RPM]
eta         = 0.97; % Mesh efficiency per pair

% --- Face Width ---
f_factor = 0.28;    % Face width / outer cone distance (0.25–0.30)

% --- 3D Print Material ---
print_material = 'PLA';   % 'PLA', 'ABS', 'PETG', 'Nylon', 'Resin', 'Steel', 'None'

% --- Mesh Resolution ---
n_inv  = 20;        % Points per involute curve (higher = smoother teeth)
n_sec  = 16;        % Cross-sections along face width
n_top  = 4;         % Points on tip arc
n_root = 4;         % Points on root arc

% --- Material Allowable Stress ---
sigma_allow_bend = 250;   % [MPa] for stress check (hardened steel)

%% ========================================================================
%  DERIVED GEOMETRY
%  ========================================================================

phi     = deg2rad(phi_deg);
Sigma_r = deg2rad(Sigma);
i_ratio = Ng / Np;

% Pitch diameters
dp = m * Np;
dg = m * Ng;

% Pitch cone angles
gamma_p = atan2(sin(Sigma_r), (Ng/Np + cos(Sigma_r)));
gamma_g = Sigma_r - gamma_p;

% Cone distances
Ao = dp / (2 * sin(gamma_p));
F  = f_factor * Ao;
Am = Ao - F/2;
Ai = Ao - F;

% Gleason Zerol: Circular-arc curved teeth generated by cutter radius Am
if isempty(r_cutter)
    r_cutter = Am;  % Gleason face-milling cutter radius (mean cone distance)
end

% Tooth dimensions
hw    = khw_factor * m;
c_std = c_factor * m;
ht    = hw + c_std;

% Gleason unequal addendum (60% pinion / 40% gear)
a_p = 0.600 * hw;
a_g = 0.400 * hw;
b_p = ht - a_p;
b_g = ht - a_g;

% Tooth thickness (Gleason balance)
s_nom   = pi * m / 2;
s_shift = 0.180 * m;
s_p     = s_nom + s_shift;     % Thickened pinion
s_g     = s_nom - s_shift;     % Thinned gear

% Outside diameters
Do_p = dp + 2 * a_p * cos(gamma_p);
Do_g = dg + 2 * a_g * cos(gamma_g);

% Back cone radius (Tregold)
rb_p = dp / (2 * cos(gamma_p));
rb_g = dg / (2 * cos(gamma_g));

% Virtual teeth
Nv_p = Np / cos(gamma_p);
Nv_g = Ng / cos(gamma_g);

% Contact ratio
rv_p  = m * Nv_p / 2;
rv_g  = m * Nv_g / 2;
rav_p = rv_p + a_p;
rav_g = rv_g + a_g;
rbv_p = rv_p * cos(phi);
rbv_g = rv_g * cos(phi);
pb    = pi * m * cos(phi);
CR = (sqrt(rav_p^2 - rbv_p^2) + sqrt(rav_g^2 - rbv_g^2) - ...
     (rv_p + rv_g) * sin(phi)) / pb;

% Mounting distances
MD_p = Ao * cos(gamma_p) - a_p * sin(gamma_p);
MD_g = Ao * cos(gamma_g) - a_g * sin(gamma_g);

% Circular & diametral pitch
pc = pi * m;
P_d = 25.4 / m;

%% ========================================================================
%  DRIVETRAIN KINEMATICS
%  ========================================================================

n_pinion_out    = n_in_ring * i_ratio;
T_ring_per_mesh = T_in_ring / n_pinions;
T_pinion_each   = (T_ring_per_mesh / i_ratio) * eta;
P_in_total      = T_in_ring * 2 * pi * n_in_ring / 60;
P_out_each      = T_pinion_each * 2 * pi * n_pinion_out / 60;

% Forces at mean cone distance
dg_mean = dg * Am / Ao;
Ft = 2 * T_ring_per_mesh * 1000 / dg_mean;
Fr_p = Ft * tan(phi) * cos(gamma_p);
Fa_p = Ft * tan(phi) * sin(gamma_p);
F_resultant = sqrt(Ft^2 + Fr_p^2 + Fa_p^2);

% Lewis bending stress
m_mean = m * Am / Ao;
Y_p = (0.484 - 2.87 / Nv_p) * (s_p / s_nom)^2;
Y_g = (0.484 - 2.87 / Nv_g) * (s_g / s_nom)^2;
sigma_b_p = Ft / (F * m_mean * Y_p);
sigma_b_g = Ft / (F * m_mean * Y_g);
SF_p = sigma_allow_bend / sigma_b_p;
SF_g = sigma_allow_bend / sigma_b_g;

%% ========================================================================
%  PRINT COMPENSATION SETUP
%  ========================================================================

ps = print_settings(print_material);

% Build crowning struct from print settings
crowning_p = struct( ...
    'lengthwise',       ps.lengthwise_crown, ...
    'profile',          ps.profile_crown, ...
    'tip_relief',       ps.tip_relief, ...
    'tip_relief_start', ps.tip_relief_start);

crowning_g = crowning_p;   % Same crowning for gear (can be different if needed)

% Adjust tooth thickness for print backlash
s_p_print = s_p - ps.extra_backlash;
s_g_print = s_g - ps.extra_backlash;

% Adjust clearance for print tolerance
c_print = c_std + ps.clearance_add;
ht_print = hw + c_print;
b_p_print = ht_print - a_p;
b_g_print = ht_print - a_g;

%% ========================================================================
%  DISPLAY SUMMARY
%  ========================================================================

fprintf('\n');
fprintf([repmat('=', 1, 70) '\n']);
fprintf('  ZEROL BEVEL GEAR DESIGN V2 — WIND TURBINE PITCH CONTROL\n');
fprintf('  Gleason Face-Milling Geometry with Curved Tooth Traces\n');
fprintf([repmat('=', 1, 70) '\n\n']);

fprintf('--- CONFIGURATION ---\n');
fprintf('  Module: %g mm  |  Teeth: %d/%d (Pinion/Gear)  |  Ratio: 1:%.1f\n', m, Np, Ng, i_ratio);
fprintf('  Pressure angle: %.1f deg  |  Shaft angle: %.1f deg\n', phi_deg, Sigma);
fprintf('  Pinions: %d  |  Cutter radius: %.1f mm\n', n_pinions, r_cutter);
fprintf('  Print material: %s\n\n', ps.description);

fprintf('--- TOOTH GEOMETRY (Gleason Unequal Addendum) ---\n');
fprintf('  %-20s  %8s  %8s\n', '', 'Pinion', 'Gear');
fprintf('  %-20s  %8.2f  %8.2f  mm\n', 'Pitch diameter', dp, dg);
fprintf('  %-20s  %8.2f  %8.2f  deg\n', 'Cone angle', rad2deg(gamma_p), rad2deg(gamma_g));
fprintf('  %-20s  %8.3f  %8.3f  mm\n', 'Addendum', a_p, a_g);
fprintf('  %-20s  %8.3f  %8.3f  mm\n', 'Dedendum', b_p, b_g);
fprintf('  %-20s  %8.3f  %8.3f  mm\n', 'Tooth thickness', s_p, s_g);
fprintf('  Working depth: %.3f mm  |  Whole depth: %.3f mm\n', hw, ht);
fprintf('  Face width: %.2f mm  |  Cone distance: %.2f mm\n', F, Ao);
fprintf('  Contact ratio: %.3f', CR);
if CR >= 1.5
    fprintf('  (GOOD)\n');
elseif CR >= 1.2
    fprintf('  (ACCEPTABLE)\n');
else
    fprintf('  *** WARNING — LOW CR ***\n');
end

fprintf('\n--- OPERATING CONDITIONS ---\n');
fprintf('  Input torque: %.1f N·m  |  Ring speed: %.0f RPM\n', T_in_ring, n_in_ring);
fprintf('  Pinion speed: %.0f RPM  |  Blade torque: %.2f N·m\n', n_pinion_out, T_pinion_each);
fprintf('  Tangential force: %.1f N  |  Safety factor: %.2f / %.2f (P/G)\n', Ft, SF_p, SF_g);
if SF_p >= 1.5 && SF_g >= 1.5
    fprintf('  Stress status: SAFE (SF >= 1.5)\n');
elseif SF_p >= 1.0 && SF_g >= 1.0
    fprintf('  Stress status: ACCEPTABLE (SF >= 1.0)\n');
else
    fprintf('  Stress status: *** WARNING — HIGH STRESS ***\n');
end

fprintf('\n--- PRINT COMPENSATION ---\n');
fprintf('  Shrinkage scale: %.4f  |  Extra backlash: %.2f mm/side\n', ...
    ps.shrinkage_factor, ps.extra_backlash);
fprintf('  Tip relief: %.2f mm  |  Crown L/P: %.3f / %.3f mm\n', ...
    ps.tip_relief, ps.lengthwise_crown, ps.profile_crown);
fprintf('  Tooth thick (print): %.3f / %.3f mm (P/G)\n', s_p_print, s_g_print);

%% ========================================================================
%  3D MESH GENERATION (Curved Gleason Teeth)
%  ========================================================================

fprintf('\n--- GENERATING 3D MESHES ---\n');
fprintf('  Building Gleason Zerol pinion (N=%d, r_c=%.1f mm)...\n', Np, r_cutter);

pinion_mesh = build_bevel_mesh_v2(Np, m, phi, a_p, b_p_print, gamma_p, ...
    Ao, F, r_cutter, n_inv, n_sec, n_top, n_root, s_p_print, crowning_p);

fprintf('  Building Gleason Zerol ring gear (N=%d, r_c=%.1f mm)...\n', Ng, r_cutter);

gear_mesh = build_bevel_mesh_v2(Ng, m, phi, a_g, b_g_print, gamma_g, ...
    Ao, F, r_cutter, n_inv, n_sec, n_top, n_root, s_g_print, crowning_g);

% Apply shrinkage compensation
if ps.shrinkage_factor ~= 1.0
    fprintf('  Applying %.1f%% shrinkage compensation...\n', (ps.shrinkage_factor-1)*100);
    pinion_mesh = print_compensation(pinion_mesh, ps.shrinkage_factor);
    gear_mesh   = print_compensation(gear_mesh, ps.shrinkage_factor);
end

fprintf('  Pinion: %d verts, %d tris\n', size(pinion_mesh.vertices,1), size(pinion_mesh.faces,1));
fprintf('  Gear:   %d verts, %d tris\n', size(gear_mesh.vertices,1), size(gear_mesh.faces,1));

