function fig1 = plot_spiral_bevel_assembly_3d(gear_mesh, pinion_mesh, calc)
%PLOT_SPIRAL_BEVEL_ASSEMBLY_3D Generates publication-grade 3D CAD assembly
%   and single-pair exploded view for a Spiral Bevel Gear pitch actuator drive.
%
%   - Subplot 1: Full 3D CAD Assembly (Central Gear + 3 Multi-Pinions on 90 deg shafts)
%   - Subplot 2: Single-Pair Exploded View (1 Pinion + 1 Gear separated along shafts)
%
%   Author: Ahmed Majdy Ahmed
%   Date:   2026-09-04

    if nargin < 3
        error('plot_spiral_bevel_assembly_3d requires gear_mesh, pinion_mesh, and calc');
    end

    n_pinions = calc.n_pinions;
    Ao = calc.Ao;
    Np = calc.Np;
    Ng = calc.Ng;
    m = calc.m;
    beta_m = calc.beta_m_deg;

    fig1 = figure('Name', 'Spiral Bevel Suite — 3D CAD Assembly & Exploded View', ...
        'NumberTitle', 'off', ...
        'Position', [50, 50, 1450, 850], ...
        'Color', [0.08 0.08 0.11], ...
        'MenuBar', 'figure', ...
        'ToolBar', 'figure');

    %% ====================================================================
    %  SUBPLOT 1: Full 3D CAD Assembly (Central Gear + 3 Pinions at 120 deg)
    %  ====================================================================
    ax1 = subplot(1, 2, 1, 'Parent', fig1);
    hold(ax1, 'on');

    % 1. Central Spiral Bevel Gear (Golden Bronze [0.78 0.52 0.28])
    patch(ax1, 'Vertices', gear_mesh.vertices, ...
        'Faces', gear_mesh.faces, ...
        'VertexNormals', gear_mesh.normals, ...
        'FaceColor', [0.78 0.52 0.28], ...
        'EdgeColor', 'none', ...
        'FaceAlpha', 0.95, ...
        'FaceLighting', 'gouraud', ...
        'AmbientStrength', 0.38, ...
        'DiffuseStrength', 0.65, ...
        'SpecularStrength', 0.35);

    % 2. 3 Multi-Pinions arranged at 120 deg on 90 deg orthogonal shafts
    pinion_colors = [0.45 0.58 0.78;   % Pinion 1: Steel Blue
                     0.55 0.75 0.55;   % Pinion 2: Sage Green
                     0.72 0.48 0.65;   % Pinion 3: Dusty Lavender
                     0.78 0.68 0.45;   % Warm Ochre
                     0.50 0.70 0.75;   % Cyan Teal
                     0.70 0.55 0.55];  % Terra Cotta

    Ry90 = [0 0 1; 0 1 0; -1 0 0];
    phi_clock = pi / Np;
    R_clock = [cos(phi_clock) -sin(phi_clock) 0; sin(phi_clock) cos(phi_clock) 0; 0 0 1];

    for p = 1:n_pinions
        angle_offset = (p - 1) * 2 * pi / n_pinions;
        c_a = cos(angle_offset);
        s_a = sin(angle_offset);
        Rz = [c_a -s_a 0; s_a c_a 0; 0 0 1];

        phase_angle = angle_offset * (Ng / Np);
        R_phase = [cos(phase_angle) -sin(phase_angle) 0; sin(phase_angle) cos(phase_angle) 0; 0 0 1];
        R_pinion = Rz * Ry90 * R_clock * R_phase;

        pin_verts = (R_pinion * pinion_mesh.vertices')';
        pin_normals = (R_pinion * pinion_mesh.normals')';

        color_idx = mod(p - 1, size(pinion_colors, 1)) + 1;
        patch(ax1, 'Vertices', pin_verts, ...
            'Faces', pinion_mesh.faces, ...
            'VertexNormals', pin_normals, ...
            'FaceColor', pinion_colors(color_idx, :), ...
            'EdgeColor', 'none', ...
            'FaceAlpha', 0.95, ...
            'FaceLighting', 'gouraud', ...
            'AmbientStrength', 0.38, ...
            'DiffuseStrength', 0.65, ...
            'SpecularStrength', 0.35);
    end

    % Lighting & Styling for Subplot 1
    light(ax1, 'Position', [1 1 1.5], 'Style', 'infinite');
    light(ax1, 'Position', [-1 -1 0.8], 'Style', 'infinite');
    light(ax1, 'Position', [0 0 -1.5], 'Style', 'infinite');
    axis(ax1, 'equal'); grid(ax1, 'on');
    xlabel(ax1, 'X [mm]'); ylabel(ax1, 'Y [mm]'); zlabel(ax1, 'Z [mm]');
    title(ax1, sprintf('3D Spiral Bevel Assembly: %d Pinions + Gear (m = %g, \\beta_m = %.0f^\\circ, Ao = %.1f mm)', ...
        n_pinions, m, beta_m, Ao), 'Color', 'w', 'FontSize', 12, 'FontWeight', 'bold');
    view(ax1, [-40 30]);
    set(ax1, 'Color', [0.12 0.12 0.16], ...
        'XColor', [0.7 0.7 0.7], 'YColor', [0.7 0.7 0.7], 'ZColor', [0.7 0.7 0.7], ...
        'GridColor', [0.25 0.25 0.30], 'GridAlpha', 0.5);

    %% ====================================================================
    %  SUBPLOT 2: Exploded View (SINGLE PAIR: 1 Pinion + 1 Central Gear)
    %  ====================================================================
    ax2 = subplot(1, 2, 2, 'Parent', fig1);
    hold(ax2, 'on');

    sep_axial  = Ao * 0.40;   % Axial separation along Z for gear
    sep_radial = Ao * 0.40;   % Radial separation along X for pinion

    % 1. Central Gear shifted downward along -Z
    gear_verts_exp = gear_mesh.vertices;
    gear_verts_exp(:, 3) = gear_verts_exp(:, 3) - sep_axial;

    patch(ax2, 'Vertices', gear_verts_exp, ...
        'Faces', gear_mesh.faces, ...
        'VertexNormals', gear_mesh.normals, ...
        'FaceColor', [0.78 0.52 0.28], ...
        'EdgeColor', 'none', ...
        'FaceAlpha', 0.95, ...
        'FaceLighting', 'gouraud', ...
        'AmbientStrength', 0.38, ...
        'DiffuseStrength', 0.65, ...
        'SpecularStrength', 0.35);

    % 2. Single Pinion (Steel Blue) shifted outward along +X shaft
    R_pinion_1 = Ry90 * R_clock;
    pin_verts_exp = (R_pinion_1 * pinion_mesh.vertices')';
    pin_normals_exp = (R_pinion_1 * pinion_mesh.normals')';
    pin_verts_exp(:, 1) = pin_verts_exp(:, 1) + sep_radial;

    patch(ax2, 'Vertices', pin_verts_exp, ...
        'Faces', pinion_mesh.faces, ...
        'VertexNormals', pin_normals_exp, ...
        'FaceColor', [0.45 0.58 0.78], ...
        'EdgeColor', 'none', ...
        'FaceAlpha', 0.95, ...
        'FaceLighting', 'gouraud', ...
        'AmbientStrength', 0.38, ...
        'DiffuseStrength', 0.65, ...
        'SpecularStrength', 0.35);

    % Shaft Axis & Exploded Motion Projection Lines
    plot3(ax2, [0 0], [0 0], [-sep_axial, 30], '--', 'Color', [1 0.8 0.2], 'LineWidth', 1.5);
    plot3(ax2, [0, sep_radial + 45], [0 0], [0 0], '--', 'Color', [0.3 0.8 1.0], 'LineWidth', 1.5);

    % Cone Apex Marker (0, 0, 0)
    plot3(ax2, 0, 0, 0, 'kp', 'MarkerFaceColor', [1 0.3 0.3], 'MarkerSize', 10);
    text(ax2, 2, 2, 4, 'Cone Apex (0,0,0)', 'Color', [1 0.5 0.5], 'FontSize', 9, 'FontWeight', 'bold');

    % Information Annotation Card
    info_str = sprintf([ ...
        '\\bfSPIRAL BEVEL DESIGN METRICS\\rm\n' ...
        'Module m: %g mm\n' ...
        'Teeth: %d / %d (Ratio 1:%.1f)\n' ...
        'Mean Spiral Angle \\beta_m: %.1f^\\circ\n' ...
        'Normal Pressure Angle: %.1f^\\circ\n' ...
        'Pitch Diameters: %.1f / %.1f mm\n' ...
        'Outer Cone Dist Ao: %.2f mm\n' ...
        'Face Width F: %.1f mm\n' ...
        'Transverse CR \\epsilon_\\alpha: %.3f\n' ...
        'Overlap Ratio \\epsilon_\\beta: %.3f\n' ...
        'Total Contact Ratio \\epsilon_\\gamma: %.3f\n' ...
        'Pinion Torque: %.2f N\\cdotm\n' ...
        'Tangential Force Ft: %.1f N\n' ...
        'Safety Factors: SF_b = %.1f / %.1f, SF_H = %.1f'], ...
        m, Np, Ng, calc.i_ratio, beta_m, calc.phi_n_deg, ...
        calc.dp, calc.dg, Ao, calc.F, ...
        calc.eps_alpha, calc.eps_beta, calc.eps_gamma, ...
        calc.T_pinion_each, calc.Ft, calc.SF_b_p, calc.SF_b_g, calc.SF_contact);

    annotation(fig1, 'textbox', [0.85, 0.46, 0.14, 0.48], ...
        'String', info_str, 'Color', 'w', 'BackgroundColor', [0.15 0.15 0.20], ...
        'EdgeColor', [0.35 0.35 0.45], 'FontSize', 8.5, 'FitBoxToText', 'on', ...
        'HitTest', 'off');

    % Lighting & Styling for Subplot 2
    light(ax2, 'Position', [1 1 1.5], 'Style', 'infinite');
    light(ax2, 'Position', [-1 -1 0.8], 'Style', 'infinite');
    light(ax2, 'Position', [0 0 -1.5], 'Style', 'infinite');
    axis(ax2, 'equal'); grid(ax2, 'on');
    xlabel(ax2, 'X [mm]'); ylabel(ax2, 'Y [mm]'); zlabel(ax2, 'Z [mm]');
    title(ax2, sprintf('Exploded Meshing View (Separation = %.1f mm)', sep_radial), ...
        'Color', 'w', 'FontSize', 12, 'FontWeight', 'bold');
    view(ax2, [-40 30]);
    set(ax2, 'Color', [0.12 0.12 0.16], ...
        'XColor', [0.7 0.7 0.7], 'YColor', [0.7 0.7 0.7], 'ZColor', [0.7 0.7 0.7], ...
        'GridColor', [0.25 0.25 0.30], 'GridAlpha', 0.5);

    % Enable full interactive 3D camera controls (Click-drag Rotate, Mouse-wheel Zoom, Right-click Zoom)
    rotate3d(fig1, 'on');

    drawnow;
end
